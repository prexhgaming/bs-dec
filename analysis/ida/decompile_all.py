# Decompile every function with IDA Pro + Hex-Rays (headless).
#
# IDA is commercial and cannot be installed on a hosted GitHub runner, so this
# path is for a self-hosted runner (or a local machine) that already has IDA with
# the ARM/ARM64 Hex-Rays decompiler:
#
#   idat -A -S"analysis/ida/decompile_all.py /tmp/ida-out 4000 5400" libGame.so
#   idat64 -A -S"analysis/ida/decompile_all.py /tmp/ida-out 4000 5400" libGame.so
#
# Arguments after the script path (all optional):
#   1. output directory            (default: /tmp/ida-out)
#   2. max functions to decompile  (default: 0 = all)
#   3. time budget in seconds      (default: 0 = no limit)
#
# Output: <out>/decompiled.c and <out>/ida-manifest.json. Function addresses in
# the comments are the join key with the capstone JSONL parts, so a Ghidra / IDA
# decompilation can be lined up against the raw disassembly.
#
# Requires IDA 7.5+ (IDAPython 3) with the Hex-Rays decompiler for the target
# architecture. Ends with qexit() so the headless run terminates by itself.

import json
import os
import time

import ida_auto
import ida_funcs
import ida_hexrays
import ida_nalt
import idautils
import idc


def script_args():
    raw = idc.ARGV[1:]
    return [str(item) for item in raw]


def main():
    args = script_args()
    out_dir = args[0] if len(args) > 0 else "/tmp/ida-out"
    max_functions = int(args[1]) if len(args) > 1 else 0
    budget_seconds = int(args[2]) if len(args) > 2 else 0

    if not os.path.isdir(out_dir):
        os.makedirs(out_dir)

    ida_auto.auto_wait()

    if not ida_hexrays.init_hexrays_plugin():
        print("[decompile_all] Hex-Rays is not available for this architecture")
        idc.qexit(3)
        return

    started = time.time()
    written = 0
    failed = 0
    total = ida_funcs.get_func_qty()
    c_path = os.path.join(out_dir, "decompiled.c")

    with open(c_path, "w") as handle:
        handle.write("// IDA Hex-Rays decompilation of %s\n" % ida_nalt.get_root_filename())
        handle.write("// Generated by analysis/ida/decompile_all.py\n\n")

        for index in range(total):
            if max_functions and written >= max_functions:
                break
            if budget_seconds and (time.time() - started) > budget_seconds:
                break
            function = ida_funcs.getn_func(index)
            if function is None:
                continue
            entry = function.start_ea
            name = ida_funcs.get_func_name(entry) or ("sub_%X" % entry)
            size = function.end_ea - function.start_ea
            try:
                code = ida_hexrays.decompile(entry)
            except Exception as exc:  # noqa: BLE001 - IDA raises its own types
                failed += 1
                handle.write("// ---- 0x%x %s (size %d) FAILED: %s\n\n" % (entry, name, size, exc))
                continue
            if code is None:
                failed += 1
                continue
            handle.write("// ---- 0x%x %s (size %d)\n" % (entry, name, size))
            handle.write(str(code))
            handle.write("\n\n")
            written += 1
            if written % 100 == 0:
                print("[decompile_all] %d functions in %.0fs" % (written, time.time() - started))

    manifest = {
        "tool": "analysis/ida/decompile_all.py",
        "engine": "ida",
        "input": ida_nalt.get_root_filename(),
        "input_sha256": ida_nalt.retrieve_input_file_sha256().hex() if hasattr(ida_nalt, "retrieve_input_file_sha256") else None,
        "functions_in_program": total,
        "functions_written": written,
        "functions_failed": failed,
        "seconds": round(time.time() - started, 1),
        "output": os.path.basename(c_path),
        "output_bytes": os.path.getsize(c_path) if os.path.exists(c_path) else 0,
    }
    with open(os.path.join(out_dir, "ida-manifest.json"), "w") as handle:
        json.dump(manifest, handle, indent=2)
        handle.write("\n")

    print("[decompile_all] done: %d functions, %d failed" % (written, failed))
    idc.qexit(0)


main()
