# Decompile every function of the imported program with Ghidra's decompiler.
#
# Run through Ghidra's headless analyzer (see .github/workflows/decompile-lib.yml):
#
#   support/analyzeHeadless /tmp/ghidra-project bloodstrike \
#       -import libGame.so \
#       -scriptPath analysis/ghidra \
#       -postScript DecompileAll.py /tmp/out 4000 5400 \
#       -deleteProject
#
# Arguments (all optional, in this order):
#   1. output directory            (default: /tmp/ghidra-out)
#   2. max functions to decompile  (default: 0 = all)
#   3. time budget in seconds      (default: 0 = no limit)
#
# Output: <out>/decompiled.c (one commented function per block) and
# <out>/ghidra-manifest.json with counts and the program's hash, so the result
# can be matched against the capstone parts and the library itself.
#
# @category BloodStrike
# @runtime Jython
# @runtime PyGhidra  (Ghidra 12 dropped Jython; this tag lets either build run it)

import json
import os
import time

from ghidra.app.decompiler import DecompInterface, DecompileOptions
from ghidra.util.task import ConsoleTaskMonitor

args = getScriptArgs()
out_dir = args[0] if len(args) > 0 else "/tmp/ghidra-out"
max_functions = int(args[1]) if len(args) > 1 else 0
budget_seconds = int(args[2]) if len(args) > 2 else 0

if not os.path.isdir(out_dir):
    os.makedirs(out_dir)

decompiler = DecompInterface()
options = DecompileOptions()
decompiler.setOptions(options)
decompiler.openProgram(currentProgram)
monitor = ConsoleTaskMonitor()

function_manager = currentProgram.getFunctionManager()
program_name = currentProgram.getName()
image_base = currentProgram.getImageBase().getOffset()

started = time.time()
written = 0
failed = 0
skipped = 0
c_path = os.path.join(out_dir, "decompiled.c")

with open(c_path, "w") as handle:
    handle.write("// Ghidra decompilation of %s (image base 0x%x)\n" % (program_name, image_base))
    handle.write("// Generated by analysis/ghidra/DecompileAll.py\n\n")

    for function in function_manager.getFunctions(True):
        if max_functions and written >= max_functions:
            break
        if budget_seconds and (time.time() - started) > budget_seconds:
            break
        name = function.getName()
        entry = function.getEntryPoint().getOffset()
        body = function.getBody()
        size = body.getNumAddresses()
        result = decompiler.decompileFunction(function, 60, monitor)
        if not result.decompileCompleted():
            failed += 1
            handle.write("// ---- 0x%x %s (size %d) FAILED: %s\n\n" % (entry, name, size, result.getErrorMessage()))
            continue
        code = result.getDecompiledFunction().getC()
        handle.write("// ---- 0x%x %s (size %d)\n" % (entry, name, size))
        handle.write("// bytes_sha256_prefix unused; address is the join key with the JSONL parts\n")
        handle.write(code)
        handle.write("\n\n")
        written += 1
        if written % 100 == 0:
            elapsed = time.time() - started
            print("[DecompileAll] %d functions in %.0fs" % (written, elapsed))

manifest = {
    "tool": "analysis/ghidra/DecompileAll.py",
    "engine": "ghidra",
    "program": program_name,
    "image_base": "0x%x" % image_base,
    "language": currentProgram.getLanguageID().getIdAsString(),
    "functions_in_program": function_manager.getFunctionCount(),
    "functions_written": written,
    "functions_failed": failed,
    "seconds": round(time.time() - started, 1),
    "output": os.path.basename(c_path),
    "output_bytes": os.path.getsize(c_path) if os.path.exists(c_path) else 0,
}

with open(os.path.join(out_dir, "ghidra-manifest.json"), "w") as handle:
    json.dump(manifest, handle, indent=2)
    handle.write("\n")

print("[DecompileAll] done: %d functions, %d failed, manifest in %s" % (written, failed, out_dir))
